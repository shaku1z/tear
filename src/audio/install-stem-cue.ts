import { installPrimaryMusicBackend } from "./music-backend-registry";
import type { MusicBackend, MusicBackendHost, MusicRunSessionMetadata } from "./music-contracts";
import { BiomeStemBackend, type LoadedCueRef } from "./stems/biome-stem-backend";
import { StemCueMusicBackend } from "./stems/stem-cue-backend";
import type { StemCueManifest } from "./stems/types";
import { parseMusicCatalog } from "./music/catalog";
import { publishMusicLibrary } from "./music/library";
import { validateMusicRoutingManifest } from "./music/music-routing-validate";

/**
 * The game's one music request before audio: `audio/music.json`, generated by
 * tear-music from every song (catalog, routing and each cue manifest). Cue audio
 * stays lazy; it is fetched when a cue is first played.
 */
async function loadMusicIndex(): Promise<BiomeStemBackend> {
  const response = await fetch(new URL("audio/music.json", document.baseURI).href);
  if (!response.ok) throw new Error(`music index unavailable (${String(response.status)})`);
  const index = (await response.json()) as {
    readonly format: string;
    readonly catalog: unknown;
    readonly routing: unknown;
    readonly cues: Readonly<Record<string, StemCueManifest>>;
  };
  if (index.format !== "tear-music-index") throw new Error(`music index format is ${index.format}`);
  const routing = validateMusicRoutingManifest(index.routing);
  const catalog = parseMusicCatalog(index.catalog);
  const cues: LoadedCueRef[] = Object.entries(index.cues).map(([id, manifest]) => ({
    id,
    manifest,
    baseUrl: `audio/cues/${id}`,
  }));
  if (!cues.some((cue) => cue.id === routing.defaultWorkId)) throw new Error("default cue missing from music index");
  const seconds = Object.fromEntries(
    cues.map(({ id, manifest }) => [
      id,
      (manifest.loop.endFrame - manifest.loop.startFrame) / manifest.sourceSampleRate,
    ]),
  );
  publishMusicLibrary(catalog.works, routing, seconds);
  return new BiomeStemBackend(cues, routing, catalog);
}

/**
 * Stands in for the stem engine until the index has loaded, so nothing about
 * music delays the first frame. AudioSystem initializes music only after the
 * player's first input; if the index failed by then, initialize throws and
 * AudioSystem's built-in music takes over.
 */
class DeferredStemBackend implements MusicBackend {
  readonly id = "stem-cue:biome-routed";
  #inner: BiomeStemBackend | null = null;
  /** A run that began before the index loaded; handed over once it has. */
  #run: MusicRunSessionMetadata | null = null;
  readonly #ready: () => Promise<BiomeStemBackend>;
  constructor(ready: () => Promise<BiomeStemBackend>) {
    this.#ready = ready;
  }
  async initialize(host: MusicBackendHost): Promise<void> {
    const inner = await this.#ready();
    await inner.initialize(host);
    this.#inner = inner;
    if (this.#run) await inner.beginRun(this.#run);
  }
  beginRun(metadata: MusicRunSessionMetadata): Promise<void> {
    this.#run = metadata;
    return this.#inner?.beginRun(metadata) ?? Promise.resolve();
  }
  updateContext(...args: Parameters<MusicBackend["updateContext"]>): void {
    this.#inner?.updateContext(...args);
  }
  emitEvent(...args: Parameters<MusicBackend["emitEvent"]>): void {
    this.#inner?.emitEvent(...args);
  }
  endRun(): Promise<void> {
    this.#run = null;
    return this.#inner?.endRun() ?? Promise.resolve();
  }
  setMuteReason(...args: Parameters<MusicBackend["setMuteReason"]>): void {
    this.#inner?.setMuteReason(...args);
  }
  replayMetadata(): ReturnType<MusicBackend["replayMetadata"]> {
    return this.#inner?.replayMetadata() ?? { enabled: false, reason: "disabled" };
  }
  resume(): Promise<void> {
    return this.#inner?.resume() ?? Promise.resolve();
  }
  suspend(): Promise<void> {
    return this.#inner?.suspend() ?? Promise.resolve();
  }
  dispose(): Promise<void> {
    return this.#inner?.dispose() ?? Promise.resolve();
  }
}

/**
 * How this session wants music. Recorded biome stems are the DEFAULT; opt out
 * with `?stems=off` (procedural engine) or audition one cue with `?stemcue=<id>`.
 * The caller passes the composition-admitted engineering query, which is empty
 * in release builds.
 */
export function requestedStemsMode(
  search: string,
): { mode: "biome" } | { mode: "single"; cueId: string } | { mode: "off" } {
  try {
    const params = new URLSearchParams(search);
    const single = params.get("stemcue");
    if (single) return { mode: "single", cueId: single };
    if (params.get("stems") === "off") return { mode: "off" };
    return { mode: "biome" };
  } catch {
    return { mode: "biome" };
  }
}

/**
 * Installs the biome-routed recorded-cue engine as the primary music backend.
 * Returns at once: the index is requested after the first frame (or when audio
 * starts, if that comes first).
 */
export function installBiomeStemBackend(): void {
  let pending: Promise<BiomeStemBackend> | null = null;
  const ready = (): Promise<BiomeStemBackend> => (pending ??= loadMusicIndex());
  // Two frames: the first paints, the second runs after it.
  requestAnimationFrame(() =>
    requestAnimationFrame(() => {
      ready().catch((error: unknown) => {
        console.warn("Music index unavailable; built-in music will play", error);
      });
    }),
  );
  installPrimaryMusicBackend(() => new DeferredStemBackend(ready));
}

/** Installs a single recorded cue, for `?stemcue=<id>` auditioning in engineering builds. */
export async function installStemCueMusicBackend(cueId: string): Promise<boolean> {
  try {
    const base = `audio/cues/${cueId}`;
    const url = new URL(`${base}/cue.json`, document.baseURI).href;
    const cue = (await fetch(url).then((response) => {
      if (!response.ok) throw new Error(`cue ${cueId} not found (${String(response.status)})`);
      return response.json();
    })) as StemCueManifest;
    installPrimaryMusicBackend(() => new StemCueMusicBackend(cue, base));
    return true;
  } catch (error) {
    console.warn(`Stem cue "${cueId}" unavailable; falling back`, error);
    return false;
  }
}
