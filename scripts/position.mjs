#!/usr/bin/env node
// Renders docs/POSITION.md from the curated config/position.json and checks that the rendered
// file is current. `pnpm position:render` writes it; `pnpm check:docs` calls checkPosition(), so
// a stale or hand-edited POSITION.md fails check:quick and CI's static.check-docs task.
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

export const POSITION_SOURCE_PATH = "config/position.json";
export const POSITION_DOCUMENT_PATH = "docs/POSITION.md";

const AREA_FIELDS = Object.freeze(["id", "name", "state", "summary", "next", "owner_action", "evidence"]);
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/u;
const AREA_ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u;
const EVIDENCE_URL = /^https:\/\/github\.com\/shaku1z\/tear\/(?:pull|issues)\/\d+$/u;

function isText(value) {
  return typeof value === "string" && value.trim() === value && !/[\r\n|]/u.test(value);
}

function validateArea(area, index, root, ids) {
  const where = `areas[${String(index)}]`;
  if (area === null || typeof area !== "object" || Array.isArray(area)) return [`${where} must be an object`];
  const errors = [];
  const extra = Object.keys(area).filter((key) => !AREA_FIELDS.includes(key));
  if (extra.length > 0) errors.push(`${where} has unknown fields: ${extra.join(", ")}`);
  if (!AREA_ID.test(String(area.id))) errors.push(`${where}.id must be kebab-case`);
  else if (ids.has(area.id)) errors.push(`${where}.id duplicates "${area.id}"`);
  else ids.add(area.id);
  for (const field of ["name", "state", "summary", "next"]) {
    if (!isText(area[field]) || area[field].length === 0)
      errors.push(`${where}.${field} must be one line of non-empty text without "|"`);
  }
  if (!isText(area.owner_action)) errors.push(`${where}.owner_action must be one line of text (may be empty)`);
  if (!Array.isArray(area.evidence) || area.evidence.length === 0) {
    errors.push(`${where}.evidence must list at least one path or pull request link`);
    return errors;
  }
  for (const entry of area.evidence) {
    if (typeof entry !== "string") errors.push(`${where}.evidence entries must be strings`);
    else if (EVIDENCE_URL.test(entry)) continue;
    else if (path.isAbsolute(entry) || entry.includes("..") || entry.includes("\\"))
      errors.push(`${where}.evidence "${entry}" must be a repository-relative path with forward slashes`);
    else if (!fs.existsSync(path.join(root, entry))) errors.push(`${where}.evidence "${entry}" does not exist`);
  }
  return errors;
}

export function validatePosition(position, root) {
  if (position === null || typeof position !== "object") return ["position must be a JSON object"];
  const errors = [];
  if (position.schema !== 1) errors.push("schema must be 1");
  if (!ISO_DATE.test(String(position.curated))) errors.push("curated must be an ISO date (YYYY-MM-DD)");
  if (!isText(position.about)) errors.push("about must be one line of text");
  const production = position.production;
  if (production === null || typeof production !== "object") errors.push("production must be an object");
  else {
    if (!/^[0-9a-f]{40}$/u.test(String(production.commit))) errors.push("production.commit must be a full SHA");
    if (!ISO_DATE.test(String(production.since))) errors.push("production.since must be an ISO date");
    if (!isText(production.site) || !isText(production.note)) errors.push("production.site and note must be text");
  }
  if (!Array.isArray(position.areas) || position.areas.length === 0) errors.push("areas must be a non-empty list");
  else {
    const ids = new Set();
    position.areas.forEach((area, index) => errors.push(...validateArea(area, index, root, ids)));
  }
  return errors;
}

function evidenceLink(entry) {
  if (EVIDENCE_URL.test(entry)) return `[#${entry.split("/").at(-1)}](${entry})`;
  return `[${entry}](${path.posix.relative("docs", entry) || "."})`;
}

export function renderPosition(position) {
  const { production } = position;
  const lines = [
    "# Tear position",
    "",
    "<!-- Generated from config/position.json by `pnpm position:render`. Do not edit this file by hand: -->",
    "<!-- pnpm check:docs fails when it differs from the render. -->",
    "",
    `Curated ${position.curated}. This page is the one place that says where each workstream stands.`,
    "Change `config/position.json` in the pull request that changes an area, then run `pnpm position:render`.",
    "",
    "## Production",
    "",
    `${production.site} runs \`${production.commit.slice(0, 8)}\` (deployed ${production.since}). ${production.note}`,
    "",
    "## Areas",
    "",
    "| Area | State | Next | Owner action |",
    "| --- | --- | --- | --- |",
    ...position.areas.map(
      (area) =>
        `| [${area.name}](#${area.id}) | ${area.state} | ${area.next} | ${area.owner_action === "" ? "—" : area.owner_action} |`,
    ),
    "",
  ];
  for (const area of position.areas) {
    lines.push(
      `<a id="${area.id}"></a>`,
      "",
      `### ${area.name}`,
      "",
      `**${area.state}.** ${area.summary}`,
      "",
      `- Next: ${area.next}`,
      `- Owner action: ${area.owner_action === "" ? "none" : area.owner_action}`,
      `- Evidence: ${area.evidence.map(evidenceLink).join(", ")}`,
      "",
    );
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function readPosition(root) {
  const sourcePath = path.join(root, POSITION_SOURCE_PATH);
  if (!fs.existsSync(sourcePath)) return { errors: [`${POSITION_SOURCE_PATH} is missing`] };
  try {
    return { position: JSON.parse(fs.readFileSync(sourcePath, "utf8")), errors: [] };
  } catch (error) {
    return { errors: [`${POSITION_SOURCE_PATH} is invalid JSON: ${error.message}`] };
  }
}

export function checkPosition(root) {
  const { position, errors } = readPosition(root);
  if (errors.length > 0) return { errors };
  const invalid = validatePosition(position, root).map((error) => `${POSITION_SOURCE_PATH}: ${error}`);
  if (invalid.length > 0) return { errors: invalid };
  const documentPath = path.join(root, POSITION_DOCUMENT_PATH);
  if (!fs.existsSync(documentPath))
    return { errors: [`${POSITION_DOCUMENT_PATH} is missing; run pnpm position:render`] };
  const actual = fs.readFileSync(documentPath, "utf8").replaceAll("\r\n", "\n");
  if (actual !== renderPosition(position))
    return {
      errors: [
        `${POSITION_DOCUMENT_PATH} is stale or was edited by hand; change ${POSITION_SOURCE_PATH} and run pnpm position:render`,
      ],
    };
  return { errors: [], areas: position.areas.length };
}

function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const command = process.argv[2];
  if (command === "render") {
    const { position, errors } = readPosition(root);
    const invalid = errors.length > 0 ? errors : validatePosition(position, root);
    if (invalid.length > 0) {
      console.error(["position source is invalid:", ...invalid.map((error) => `- ${error}`)].join("\n"));
      process.exitCode = 1;
      return;
    }
    fs.writeFileSync(path.join(root, POSITION_DOCUMENT_PATH), renderPosition(position), "utf8");
    console.log(`rendered ${POSITION_DOCUMENT_PATH} (${String(position.areas.length)} areas)`);
  } else if (command === "check") {
    const result = checkPosition(root);
    if (result.errors.length > 0) {
      console.error(result.errors.join("\n"));
      process.exitCode = 1;
      return;
    }
    console.log(`${POSITION_DOCUMENT_PATH} is current (${String(result.areas)} areas)`);
  } else {
    console.error("Usage: node scripts/position.mjs <render|check>");
    process.exitCode = 1;
  }
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
