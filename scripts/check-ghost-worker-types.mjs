import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";
import process from "node:process";

const projectRoot = resolve(import.meta.dirname, "..");
const workersRoot = resolve(projectRoot, "workers");
const target = resolve(workersRoot, "worker-configuration.d.ts");
const candidate = resolve(workersRoot, `.worker-configuration.${String(process.pid)}.d.ts`);
const wranglerCli = resolve(projectRoot, "node_modules", "wrangler", "bin", "wrangler.js");
const config = resolve(projectRoot, "wrangler.ghost.jsonc");
const write = process.argv.includes("--write");

function normalizeLineEndings(value) {
  return value.replaceAll("\r\n", "\n");
}

function normalizeGenerated(value) {
  return normalizeLineEndings(value)
    .replace(
      /^\/\/ Generated by Wrangler by running .* \(hash: ([0-9a-f]+)\)$/mu,
      "// Generated by Wrangler by running `wrangler types --config=wrangler.ghost.jsonc workers/worker-configuration.d.ts` (hash: $1)",
    )
    .replace(/[ \t]+$/gmu, "");
}

try {
  const result = spawnSync(process.execPath, [wranglerCli, "types", candidate, "--config", config], {
    cwd: projectRoot,
    encoding: "utf8",
    stdio: "pipe",
  });
  if (result.error !== undefined) throw result.error;
  if (result.status !== 0) {
    process.stdout.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Wrangler type generation failed with exit code ${String(result.status)}`);
  }

  const generated = normalizeGenerated(readFileSync(candidate, "utf8"));
  if (write) {
    writeFileSync(target, generated, "utf8");
    console.log(`Wrote normalized Ghost Worker types: ${target.replaceAll("\\", "/")}`);
  } else {
    if (!existsSync(target) || normalizeLineEndings(readFileSync(target, "utf8")) !== generated) {
      throw new Error("Ghost Worker types are out of date; run pnpm generate:ghost-types");
    }
    console.log("PASS Ghost Worker generated types are current");
  }
} finally {
  rmSync(candidate, { force: true });
}
